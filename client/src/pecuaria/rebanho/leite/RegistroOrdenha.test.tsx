it("salva somente a nova parcela e mantém parcelas intactas, confirmadas e históricas na mesma ordem", async () => {
  const confirmada = { ...medicao, id: "m-confirmada", entradaId: "e1", recipiente: "Confirmada" };
  const historica = { ...medicao, id: "m-historica", natureza: null, recipiente: "Histórica" };
  const nova = { ...novaParcela("NAO_COMERCIAL", [], true), recipiente: "Nova origem", litros: "12", responsavel: "Ana", justificativa: "Separada diretamente em campo", produto: "p2", motivo: "Nova natureza conferida" };
  const intacta = { ...parcelaSalva(medicao), produto: "p1", motivo: "Natureza preservada" };
  armazenar([intacta, parcelaSalva(confirmada), parcelaSalva(historica), nova], true);
  vi.mocked(contextoParcelas).mockResolvedValue(contexto([medicao, confirmada, historica]));
  vi.mocked(salvarParcelas).mockResolvedValue({ sessaoId: "s1", parcelas: [{ ...medicao, id: "m-nova", recipiente: "Nova origem", litros: 12 }] });
  abrir();
  fireEvent.click(await screen.findByRole("button", { name: "Salvar ordenha" }));
  await screen.findByText("Ordenha salva. A entrada no estoque permanece pendente.");
  expect(salvarParcelas).toHaveBeenCalledTimes(1);
  expect(vi.mocked(salvarParcelas).mock.calls[0][3]).toEqual([expect.objectContaining({ recipiente: "Nova origem", litros: 12, versaoEsperada: 0 })]);
  const cache = JSON.parse(sessionStorage.getItem(chaveRascunhoOrdenha(1, "s1"))!);
  expect(cache.parcelas.map((p: { id: string }) => p.id)).toEqual(["m1", "m-confirmada", "m-historica", "m-nova"]);
  expect(cache.parcelas[0]).toEqual(intacta);
  expect(cache.parcelas[1]).toMatchObject({ entradaId: "e1" });
  expect(cache.parcelas[2]).toMatchObject({ classificacaoPendente: true });
  expect(cache.parcelas[3]).toMatchObject({ chave: nova.chave, produto: "p2", motivo: "Nova natureza conferida" });
  fireEvent.click(screen.getByRole("button", { name: "Salvar ordenha" }));
  expect(salvarParcelas).toHaveBeenCalledTimes(1);
});
