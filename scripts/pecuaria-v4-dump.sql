/* Extração técnica V4: SELECT em snapshot, nunca no FDB vivo.
 * Cada prefixo tem campos documentados em build-pecuaria-v4-json.mjs.
 * Não usa caches ANIMALINFO como fatos, nem seleciona BLOB. */
SET HEADING OFF;
SET WIDTH LINHA 16000;
SET TRANSACTION READ ONLY;
SELECT '@R@' || COALESCE(CAST(r.CDREPRODUCAO AS VARCHAR(255)), '')
  || '~|~' || COALESCE(CAST(r.CDTIPOREPRODUCAO AS VARCHAR(255)), '')
  || '~|~' || COALESCE(CAST(r.CDANIMAL AS VARCHAR(255)), '')
  || '~|~' || COALESCE(CAST(r.DATA AS VARCHAR(255)), '')
  || '~|~' || COALESCE(CAST(r.HORA AS VARCHAR(255)), '')
  || '~|~' || COALESCE(CAST(r.CDREPRODUTOR AS VARCHAR(255)), '')
  || '~|~' || COALESCE(CAST(r.CDEMBRIAO AS VARCHAR(255)), '')
  || '~|~' || COALESCE(CAST(r.CDDIAGNOSTICO AS VARCHAR(255)), '')
  || '~|~' || COALESCE(CAST(r.DIAGNOSTICO AS VARCHAR(255)), '')
  || '~|~' || COALESCE(CAST(r.COMPLEMENTODIAGNOSTICO AS VARCHAR(255)), '')
  || '~|~' || COALESCE(CAST(r.DTPARTOPROVAVEL AS VARCHAR(255)), '')
  || '~|~' || COALESCE(CAST(r.CDTIPOPARTO AS VARCHAR(255)), '')
  || '~|~' || COALESCE(CAST(r.NUMCRIA AS VARCHAR(255)), '')
  || '~|~' || COALESCE(CAST(r.CDANIMALCRIA1 AS VARCHAR(255)), '')
  || '~|~' || COALESCE(CAST(r.CDANIMALCRIA2 AS VARCHAR(255)), '')
  || '~|~' || COALESCE(CAST(r.SEXOCRIA1 AS VARCHAR(255)), '')
  || '~|~' || COALESCE(CAST(r.SEXOCRIA2 AS VARCHAR(255)), '')
  || '~|~' || COALESCE(CAST(r.NUMDOSES AS VARCHAR(255)), '')
  || '~|~' || COALESCE(CAST(r.CDLACTACAO AS VARCHAR(255)), '')
  || '~|~' || COALESCE(CAST(r.CDPROGRAMACAOIATF AS VARCHAR(255)), '')
  || '~|~' || COALESCE(CAST(r.CDPROTOCOLOIATF AS VARCHAR(255)), '')
  || '~|~' || COALESCE(CAST(r.CDPESSOA AS VARCHAR(255)), '')
  || '~|~' || COALESCE(CAST(r.CDRESPONSAVEL AS VARCHAR(255)), '')
  || '~|~' || COALESCE(CAST(r.CDANIMALPERIODO AS VARCHAR(255)), '')
  || '~|~' || COALESCE(CAST(r.CDCOLETA AS VARCHAR(255)), '')
  || '~|~' || COALESCE(CAST(r.CDLOTEPRODUTO AS VARCHAR(255)), '') AS LINHA
FROM REPRODUCAO r
ORDER BY r.CDREPRODUCAO;

SELECT '@L@' || COALESCE(CAST(l.CDLACTACAO AS VARCHAR(255)), '')
  || '~|~' || COALESCE(CAST(l.CDANIMAL AS VARCHAR(255)), '')
  || '~|~' || COALESCE(CAST(l.DTINICIO AS VARCHAR(255)), '')
  || '~|~' || COALESCE(CAST(l.DTFIM AS VARCHAR(255)), '')
  || '~|~' || COALESCE(CAST(l.CDMOTIVOSECAGEM AS VARCHAR(255)), '')
  || '~|~' || COALESCE(CAST(l.INDUZIDA AS VARCHAR(255)), '') AS LINHA
FROM LACTACAO l
ORDER BY l.CDLACTACAO;

SELECT '@P@' || COALESCE(CAST(p.CDANIMALPERIODO AS VARCHAR(255)), '')
  || '~|~' || COALESCE(CAST(p.CDANIMAL AS VARCHAR(255)), '')
  || '~|~' || COALESCE(CAST(p.TIPO AS VARCHAR(255)), '')
  || '~|~' || COALESCE(CAST(p.DATAINICIO AS VARCHAR(255)), '')
  || '~|~' || COALESCE(CAST(p.DATAFIM AS VARCHAR(255)), '') AS LINHA
FROM ANIMALPERIODO p
ORDER BY p.CDANIMALPERIODO;

SELECT '@A@' || COALESCE(CAST(a.CDANIMAL AS VARCHAR(255)), '')
  || '~|~' || COALESCE(CAST(a.TIPOANIMAL AS VARCHAR(255)), '')
  || '~|~' || COALESCE(CAST(a.ANIMALREBANHO AS VARCHAR(255)), '')
  || '~|~' || COALESCE(CAST(a.NUMERO AS VARCHAR(255)), '')
  || '~|~' || COALESCE(CAST(a.NOME AS VARCHAR(255)), '')
  || '~|~' || COALESCE(CAST(a.SEXO AS VARCHAR(255)), '')
  || '~|~' || COALESCE(CAST(a.DTNASCIMENTO AS VARCHAR(255)), '')
  || '~|~' || COALESCE(CAST(a.DTENTFAZENDA AS VARCHAR(255)), '')
  || '~|~' || COALESCE(CAST(a.NUMPARTOENTRADA AS VARCHAR(255)), '')
  || '~|~' || COALESCE(CAST(a.DTAPTIDAO AS VARCHAR(255)), '')
  || '~|~' || COALESCE(CAST(a.CDMAE AS VARCHAR(255)), '')
  || '~|~' || COALESCE(CAST(a.CDPAI AS VARCHAR(255)), '')
  || '~|~' || COALESCE(CAST(a.CDPRODUTO AS VARCHAR(255)), '') AS LINHA
FROM ANIMAL a
ORDER BY a.CDANIMAL;

SELECT '@I@' || COALESCE(CAST(p.CDPROGRAMACAOIATF AS VARCHAR(255)), '')
  || '~|~' || COALESCE(CAST(p.NOME AS VARCHAR(255)), '')
  || '~|~' || COALESCE(CAST(p.DTIMPLANTE AS VARCHAR(255)), '')
  || '~|~' || COALESCE(CAST(p.HORAIMPLANTE AS VARCHAR(255)), '')
  || '~|~' || COALESCE(CAST(p.DTRETIRADA AS VARCHAR(255)), '')
  || '~|~' || COALESCE(CAST(p.CDRESPONSAVELIMPLANTE AS VARCHAR(255)), '')
  || '~|~' || COALESCE(CAST(p.CDRESPONSAVELRETIRADA AS VARCHAR(255)), '')
  || '~|~' || COALESCE(CAST(p.CDSETOR AS VARCHAR(255)), '') AS LINHA
FROM PROGRAMACAOIATF p
ORDER BY p.CDPROGRAMACAOIATF;

SELECT '@S@' || COALESCE(CAST(s.CDPROGRAMACAOIATFASSOCIACAO AS VARCHAR(255)), '')
  || '~|~' || COALESCE(CAST(s.CDPROGRAMACAOIATF AS VARCHAR(255)), '')
  || '~|~' || COALESCE(CAST(s.CDANIMAL AS VARCHAR(255)), '')
  || '~|~' || COALESCE(CAST(s.IMPLANTE AS VARCHAR(255)), '')
  || '~|~' || COALESCE(CAST(s.PERDA AS VARCHAR(255)), '')
  || '~|~' || COALESCE(CAST(s.CDPROTOCOLOIATF AS VARCHAR(255)), '') AS LINHA
FROM PROGRAMACAOIATFASSOCIACAO s
ORDER BY s.CDPROGRAMACAOIATFASSOCIACAO;

SELECT '@T@' || COALESCE(CAST(t.CDPROTOCOLOIATF AS VARCHAR(255)), '')
  || '~|~' || COALESCE(CAST(t.DESCRICAO AS VARCHAR(255)), '')
  || '~|~' || COALESCE(CAST(t.ATIVO AS VARCHAR(255)), '') AS LINHA
FROM PROTOCOLOIATF t
ORDER BY t.CDPROTOCOLOIATF;

SELECT '@E@' || COALESCE(CAST(e.CDPROTOCOLOIATFPRINCIPIOATIVO AS VARCHAR(255)), '')
  || '~|~' || COALESCE(CAST(e.CDPROTOCOLOIATF AS VARCHAR(255)), '')
  || '~|~' || COALESCE(CAST(e.CDPRINCIPIOATIVO AS VARCHAR(255)), '')
  || '~|~' || COALESCE(CAST(e.DIA AS VARCHAR(255)), '')
  || '~|~' || COALESCE(CAST(e.CDPRODUTO AS VARCHAR(255)), '') AS LINHA
FROM PROTOCOLOIATFPRINCIPIOATIVO e
ORDER BY e.CDPROTOCOLOIATFPRINCIPIOATIVO;

SELECT '@TP@' || COALESCE(CAST(p.CDTIPOPARTO AS VARCHAR(255)), '')
  || '~|~' || COALESCE(CAST(p.DESCRICAO AS VARCHAR(255)), '') AS LINHA
FROM TIPOPARTO p
ORDER BY p.CDTIPOPARTO;

SELECT '@MS@' || COALESCE(CAST(m.CDMOTIVOSECAGEM AS VARCHAR(255)), '')
  || '~|~' || COALESCE(CAST(m.DESCRICAO AS VARCHAR(255)), '') AS LINHA
FROM MOTIVOSECAGEM m
ORDER BY m.CDMOTIVOSECAGEM;

SELECT '@CONTAGEM@R~|~' || CAST(COUNT(*) AS VARCHAR(20)) AS LINHA FROM REPRODUCAO;
SELECT '@CONTAGEM@L~|~' || CAST(COUNT(*) AS VARCHAR(20)) AS LINHA FROM LACTACAO;
SELECT '@CONTAGEM@P~|~' || CAST(COUNT(*) AS VARCHAR(20)) AS LINHA FROM ANIMALPERIODO;
SELECT '@CONTAGEM@A~|~' || CAST(COUNT(*) AS VARCHAR(20)) AS LINHA FROM ANIMAL;
SELECT '@CONTAGEM@I~|~' || CAST(COUNT(*) AS VARCHAR(20)) AS LINHA FROM PROGRAMACAOIATF;
SELECT '@CONTAGEM@S~|~' || CAST(COUNT(*) AS VARCHAR(20)) AS LINHA FROM PROGRAMACAOIATFASSOCIACAO;
SELECT '@CONTAGEM@T~|~' || CAST(COUNT(*) AS VARCHAR(20)) AS LINHA FROM PROTOCOLOIATF;
SELECT '@CONTAGEM@E~|~' || CAST(COUNT(*) AS VARCHAR(20)) AS LINHA FROM PROTOCOLOIATFPRINCIPIOATIVO;
SELECT '@CONTAGEM@TP~|~' || CAST(COUNT(*) AS VARCHAR(20)) AS LINHA FROM TIPOPARTO;
SELECT '@CONTAGEM@MS~|~' || CAST(COUNT(*) AS VARCHAR(20)) AS LINHA FROM MOTIVOSECAGEM;
SELECT '@V4@FIM' AS LINHA FROM RDB$DATABASE;

ROLLBACK;
QUIT;
